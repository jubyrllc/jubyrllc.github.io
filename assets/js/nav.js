/* ============================================================
   THE NAV BAR — one behaviour file for every page.

   The markup is generated by tools/build-nav.js and is byte-for-byte
   the same on every page except the cold screen (index.html); this is
   the matching behaviour, so the bar can't act differently depending
   on which page you opened it from either. It used to live in seven
   copy-pasted inline <script> blocks plus script.js, patio-script.js
   and fabrika-script.js — ten places to fix a nav bug in.

   Loaded before those page scripts on every page that has a nav. It
   binds once (__mglNavBound) and no-ops if something loads it twice.
   ============================================================ */
(function(){
  'use strict';

  if (window.__mglNavBound) return;

  var nav       = document.getElementById('nav');
  var burger    = document.getElementById('burger');
  var navMobile = document.getElementById('navMobile');
  if (!nav) return;

  window.__mglNavBound = true;

  /* ---- hairline under the bar, once you've scrolled off the top ---- */
  window.addEventListener('scroll', function(){
    nav.classList.toggle('is-scrolled', window.scrollY > 8);
  }, { passive: true });
  nav.classList.toggle('is-scrolled', window.scrollY > 8);

  /* ---- desktop category dropdowns ----
     Click to open, only one at a time, closes on outside click or Esc. */
  (function navDropdowns(){
    var drops = Array.prototype.slice.call(document.querySelectorAll('.navdrop'));
    if (!drops.length) return;

    function closeAll(except){
      drops.forEach(function(d){
        if (d === except) return;
        d.classList.remove('is-open');
        var t = d.querySelector('.navdrop__trigger');
        if (t) t.setAttribute('aria-expanded', 'false');
      });
    }

    drops.forEach(function(drop){
      var trigger = drop.querySelector('.navdrop__trigger');
      if (!trigger) return;
      trigger.addEventListener('click', function(e){
        e.stopPropagation();
        var willOpen = !drop.classList.contains('is-open');
        closeAll();
        drop.classList.toggle('is-open', willOpen);
        trigger.setAttribute('aria-expanded', willOpen ? 'true' : 'false');
      });
    });

    document.addEventListener('click', function(){ closeAll(); });
    document.addEventListener('keydown', function(e){
      if (e.key === 'Escape') closeAll();
    });
  })();

  /* ---- burger + mobile sheet ---- */
  if (burger && navMobile){
    burger.addEventListener('click', function(){
      var open = navMobile.classList.toggle('is-open');
      burger.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
    navMobile.addEventListener('click', function(e){
      if (e.target.closest('a')){
        navMobile.classList.remove('is-open');
        burger.setAttribute('aria-expanded', 'false');
      }
    });
  }

  /* ---- mobile accordion groups ---- */
  Array.prototype.forEach.call(document.querySelectorAll('.navmob__group'), function(group){
    var head = group.querySelector('.navmob__head');
    if (!head) return;
    head.addEventListener('click', function(){
      var open = group.classList.toggle('is-open');
      head.setAttribute('aria-expanded', open ? 'true' : 'false');
    });
  });
})();
